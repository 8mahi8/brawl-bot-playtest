// BRAWL school-iPad direct HTML embeds: identical gameplay, no external game resources.
// In Google Sites paste the standalone HTML (not the GitHub Pages URL).
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const {chromium}=require('playwright-core');
const root=path.resolve(__dirname,'..');
const variants=[
 {source:'foundation/1v1-foundation-v1.html',embed:'sites/1vs1-ipad-bot-embed.html',qa:'__brawlV29QA',mode:'1vs1'},
 {source:'foundation/2v2-ipad-safari.html',embed:'sites/2vs2-ipad-bot-embed.html',qa:'__brawlV3QA',mode:'2vs2'}
];
function exportEmbed(source,mode){
 if(mode==='1vs1')return source
  .replace(/<a class="offlineNav" href="\.\/2v2-stealth-clean-test\.html">[^<]*<\/a>/,'')
  .replace("<!-- GENERATED BY scripts/build-brawl.cjs; EDIT THE SHARED CONTRACT OR SOURCE TEMPLATE, NOT THIS FILE. MODE: 1vs1. Standalone; retains original CSP. -->",
"<!-- School Google Sites HTML-code embed. BOT-only standalone; source: foundation/1v1-foundation-v1.html. Re-export when source changes. -->")
  .replace("BRAWL 1vs1 | Shared Foundation V1","BRAWL 1vs1 | School iPad BOT");
 return source
  .replace(/<a href="\.\/1v1-stealth-clean-test\.html"[^>]*>[^<]*<\/a>/,'')
  .replace(/<!-- iPAD SAFARI CANDIDATE: generated from Team Guard LAB; no battle-rules changes\. -->/,
"<!-- School Google Sites HTML-code embed; iPad Safari BOT-only. Source: foundation/2v2-ipad-safari.html. -->")
  .replace("<title>BRAWL 2vs2 | iPad Safari</title>","<title>BRAWL 2vs2 | School iPad BOT</title>");
}
for(const v of variants){
 const source=fs.readFileSync(path.join(root,v.source),'utf8'),actual=fs.readFileSync(path.join(root,v.embed),'utf8');
 assert.equal(actual,exportEmbed(source,v.mode),v.mode+' direct embed drifted from verified source');
 assert.match(actual,/connect-src 'none'/,'do not request remote URLs');
 assert.doesNotMatch(actual,/<script[^>]+src=/,'no external JS');
 assert.doesNotMatch(actual,/href=["']\.\//,'mode navigation must belong to Google Sites');
 assert.match(actual,/<!DOCTYPE html>/,'standalone html');
 assert.match(actual,/<\/html>\s*$/,'full HTML file');
 const scripts=[...actual.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)];
 assert(scripts.length>0,'inline script exists');
 for(const [i,s]of scripts.entries())if(s[1].trim())new vm.Script(s[1],{filename:v.embed+'#'+i});
 if(v.mode==='2vs2')for(const token of ['viewport-fit=cover','visualViewport?.addEventListener','height:100dvh','ipadReady:true'])
  assert(actual.includes(token),'iPad Safari adaptation: '+token);
 console.log('PASS '+v.mode+' code/source parity, inline JS syntax and no network assets');
}
(async()=>{
 const browserBinary=['/usr/bin/google-chrome','/usr/bin/google-chrome-stable','/usr/bin/chromium','/usr/bin/chromium-browser'].find(fs.existsSync);
 if(!browserBinary)throw Error('Chromium not installed');
 const browser=await chromium.launch({headless:true,executablePath:browserBinary,args:['--no-sandbox','--disable-dev-shm-usage']});
 try{
 for(const v of variants){
  const context=await browser.newContext({viewport:{width:844,height:390},hasTouch:true,isMobile:true,deviceScaleFactor:2});
  const page=await context.newPage(),errors=[],httpRequests=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(/^https?:/.test(r.url()))httpRequests.push(r.url());});
  try {
   await page.goto('file://'+path.join(root,v.embed),{waitUntil:'load'});
   await page.waitForFunction(key=>typeof window[key]==='function',v.qa,{timeout:12000});
   await page.locator('#soloBtn').click();
   await page.waitForFunction(({key,mode})=>{const q=window[key]();return q.solo && q.scene===(mode==='1vs1'?'select':'lobby');},{key:v.qa,mode:v.mode},{timeout:12000});
   await page.locator('#readyBtn').click();
   await page.waitForFunction(({key,mode})=>{const q=window[key]();return mode==='1vs1'?q.scene==='game'&&q.game?.phase==='playing':q.scene==='game'&&q.game==='playing';},{key:v.qa,mode:v.mode},{timeout:16000});
   assert.equal(errors.length,0,'uncaught JS: '+errors.join(' / '));
   assert.deepEqual(httpRequests,[],"game must not load remote scripts on school iPad");
   if(v.mode==='2vs2')assert((await page.evaluate(()=>window.__brawlV3QA())).ipadReady,'iPad shell flag');
   console.log('PASS '+v.mode+' landscape/touch BOT match started, JS errors=0, external requests=0');
  }finally {await context.close();}
 }
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
