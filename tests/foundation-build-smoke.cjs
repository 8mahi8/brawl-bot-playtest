// BRAWL generated-build contract and reproducibility regression.
'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const build=require('../scripts/build-brawl.cjs');
const {render,contract,settings}=build;
const sources={};
for(const [name,mode]of Object.entries(settings.modes)){
 const html=render(name);sources[name]=html;
 assert.equal(html,fs.readFileSync(mode.output,'utf8'),name+' generated file must be reproducible');
 assert(html.includes('GENERATED BY scripts/build-brawl.cjs'),name+' generated marker');
 assert(html.includes("script-src 'unsafe-inline'"),name+' standalone CSP');
 assert(!/<script\b[^>]*\bsrc\s*=/i.test(html),name+' cannot require external JS');
 const script=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
 assert(script&&script.length>90000,name+' complete inline JS');
 new vm.Script(script,{filename:name+'.html'});
 const start=script.indexOf('/* BEGIN COMBAT CORE'),end=script.indexOf('/* END COMBAT CORE',start);
 assert(start>=0&&end>start,'combat module retained '+name);
 const sandbox={structuredClone};vm.runInNewContext(script.slice(start,end),sandbox);
 const b=sandbox.BrawlCombatV8.balance;
 for(const [k,v]of Object.entries(contract.common.balance))assert.equal(b[k],v,name+' balance '+k);
 assert.equal(b.areaRadius,mode.areaRadius,name+' areaRadius mode exception');
 assert.equal(b.regenDelayMs,contract.common.regenDelayMs,'regen common');
 assert.equal(b.gunnerBurstNormalMs,contract.common.gunnerBurstNormalMs,'burst common');
 assert.equal(b.ultGainDealt,contract.common.ultGainDealt,'ult common');
 const charsStart=script.indexOf('const CHARS'),charsEnd=script.indexOf('};',charsStart)+2;
 assert(charsStart>=0&&charsEnd>charsStart,'runtime CHARS '+name);
 const chars=vm.runInNewContext(script.slice(charsStart,charsEnd).replace(/^const CHARS\s*=/,'(').replace(/;$/,'')+')',{BALANCE:b});
 for(const [id,spec]of Object.entries(contract.common.characters)){
  assert.equal(chars[id].hp,spec.hp,name+': '+id+' HP');
  assert.equal(chars[id].speed,contract.common.movementSpeed,name+': '+id+' speed');
  assert.equal(chars[id].damage,spec.baseDamage,name+': '+id+' damage');
  assert.equal(chars[id].range,spec.range,name+': '+id+' range');
  assert(Math.abs(chars[id].reload*(name==='1vs1'?1000:1)-spec.reloadMs)<=1,name+': '+id+' reload');
 }
 console.log('PASS '+name+': generated code, CSP, shared combat, mode exceptions, 4 characters');
}
// IMPORTANT: prove the source contract changes BOTH modes, not just the compare/report test.
const next=structuredClone(contract);next.common.movementSpeed=104;
for(const name of Object.keys(settings.modes)){
 const changed=render(name,null,next);
 assert(changed.includes('speed:104'),'contract change propagated to '+name);
 assert(!changed.includes('speed:102'),'stale shared speed in '+name);
 assert.notEqual(changed,sources[name],'regeneration changed bytes '+name);
}
const nextDamage=structuredClone(contract);nextDamage.common.balance.tankNearDamage=12;nextDamage.common.characters.tank.baseDamage=12;
for(const name of Object.keys(settings.modes)){
 const changed=render(name,null,nextDamage);
 assert(changed.includes('tankNearDamage:12'),'damage propagated to '+name);
 assert.notEqual(changed,sources[name],'damage makes rebuilt output differ '+name);
}
const nextAbility=structuredClone(contract);
nextAbility.common.abilityRules.sniperLaserMs=720;
for(const name of Object.keys(settings.modes)){
 const changed=render(name,null,nextAbility);
 assert(changed.includes('sniperLaserMs:720'),'shared ULT timer propagates to '+name);
 assert(!changed.includes('sniperLaserMs:600'),'old sniper timer does not remain in '+name);
 assert.notEqual(changed,sources[name],'ability contract affects '+name+' generated output');
}
console.log('PASS: common GAD/ULT contract edits propagate to both game builds');
// No accidental mode cross-wiring: HP/character changes must not rewrite legacy templates.
assert.equal(settings.modes['1vs1'].template,'src/modes/1v1.template.html');
assert.equal(settings.modes['2vs2'].template,'src/modes/2v2.template.html');
assert(sources['2vs2'].includes('quietR41:true'),'quiet playtest carried into generated build');
assert(sources['1vs1'].includes('window.__brawlV29QA'),'existing 1v1 solo debug hook retained');
console.log('PASS: one contract change rebakes BOTH actual standalone games');
console.log('PASS: originals are preserved, mode-specific architecture remains separate and explicit');
